#!/usr/bin/env python3
"""Builds the shipped dictionary assets from the curated, ranked word lists.

Frequencies follow a Zipf-like curve from rank: freq = 20000 / (rank + 8) ** 0.9,
which keeps function words well ahead while still giving rare words a usable score.

Usage: python3 tools/build_dictionaries.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "app", "src", "main", "assets")
ETHIOPIC = re.compile(r"^[ሀ-፿ⶀ-⷟꬀-꬯]+$")
LATIN = re.compile(r"^[a-z']+$")


def build(src, dst, valid):
    seen, out = set(), []
    with open(os.path.join(HERE, src), encoding="utf-8") as f:
        for line in f:
            w = line.strip()
            if not w or w.startswith("#") or w in seen:
                continue
            if not valid.match(w):
                raise SystemExit(f"{src}: invalid word {w!r}")
            seen.add(w)
            out.append(w)
    with open(os.path.join(ASSETS, dst), "w", encoding="utf-8") as f:
        f.write("# generated by tools/build_dictionaries.py - word<TAB>frequency\n")
        for rank, w in enumerate(out, 1):
            f.write(f"{w}\t{max(1, int(20000 / (rank + 8) ** 0.9))}\n")
    return seen


def bigrams(src, dst, words, valid):
    with open(os.path.join(HERE, src), encoding="utf-8") as f, \
         open(os.path.join(ASSETS, dst), "w", encoding="utf-8") as o:
        o.write("# generated by tools/build_dictionaries.py - prev<TAB>word<TAB>count\n")
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            p, w, c = line.split()
            for x in (p, w):
                if not valid.match(x):
                    raise SystemExit(f"{src}: invalid word {x!r}")
                if x not in words:
                    raise SystemExit(f"{src}: {x!r} missing from word list")
            o.write(f"{p}\t{w}\t{int(c)}\n")


os.makedirs(ASSETS, exist_ok=True)
am = build("amharic_words_ranked.txt", "amharic_words.tsv", ETHIOPIC)
bigrams("amharic_bigrams.txt", "amharic_bigrams.tsv", am, ETHIOPIC)
en = build("english_words_ranked.txt", "english_words.tsv", LATIN)
bigrams("english_bigrams.txt", "english_bigrams.tsv", en, LATIN)
print(f"amharic: {len(am)} words, english: {len(en)} words")
