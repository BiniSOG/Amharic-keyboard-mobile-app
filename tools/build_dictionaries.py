#!/usr/bin/env python3
"""Builds the shipped dictionary assets from the curated, ranked word lists.

Frequencies follow a Zipf-like curve from rank: freq = 20000 / (rank + 8) ** 0.9,
which keeps function words well ahead while still giving rare words a usable score.

Usage: python3 tools/build_dictionaries.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "app", "src", "main", "assets")
ETHIOPIC = re.compile(r"^[ሀ-፿ⶀ-⷟꬀-꬯]+$")
LATIN = re.compile(r"^[a-z']+$")


def build(src, dst, valid):
    seen, out = set(), []
    with open(os.path.join(HERE, src), encoding="utf-8") as f:
        for line in f:
            w = line.strip()
            if not w or w.startswith("#") or w in seen:
                continue
            if not valid.match(w):
                raise SystemExit(f"{src}: invalid word {w!r}")
            seen.add(w)
            out.append(w)
    with open(os.path.join(ASSETS, dst), "w", encoding="utf-8") as f:
        f.write("# generated by tools/build_dictionaries.py - word<TAB>frequency\n")
        for rank, w in enumerate(out, 1):
            f.write(f"{w}\t{max(1, int(20000 / (rank + 8) ** 0.9))}\n")
    return seen


def bigrams(src, dst, words, valid):
    with open(os.path.join(HERE, src), encoding="utf-8") as f, \
         open(os.path.join(ASSETS, dst), "w", encoding="utf-8") as o:
        o.write("# generated by tools/build_dictionaries.py - prev<TAB>word<TAB>count\n")
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            p, w, c = line.split()
            for x in (p, w):
                if not valid.match(x):
                    raise SystemExit(f"{src}: invalid word {x!r}")
                if x not in words:
                    raise SystemExit(f"{src}: {x!r} missing from word list")
            o.write(f"{p}\t{w}\t{int(c)}\n")


def merge_wordfreq(src, dst, curated):
    """English: the large wordfreq export plus any curated words it lacks."""
    path = os.path.join(HERE, src)
    if not os.path.exists(path):
        return curated
    freq = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            w, c = line.rstrip("\n").split("\t")
            freq[w] = int(c)
    for w in sorted(curated):
        freq.setdefault(w, 5)
    with open(os.path.join(ASSETS, dst), "w", encoding="utf-8") as f:
        f.write("# generated by tools/build_dictionaries.py from wordfreq (CC BY-SA 4.0) + curated words\n")
        for w, c in sorted(freq.items(), key=lambda kv: (-kv[1], kv[0])):
            f.write(f"{w}\t{c}\n")
    return set(freq)


os.makedirs(ASSETS, exist_ok=True)
am = build("amharic_words_ranked.txt", "amharic_words.tsv", ETHIOPIC)
bigrams("amharic_bigrams.txt", "amharic_bigrams.tsv", am, ETHIOPIC)
en = build("english_words_ranked.txt", "english_words.tsv", LATIN)
en = merge_wordfreq("english_words_freq.tsv", "english_words.tsv", en)
bigrams("english_bigrams.txt", "english_bigrams.tsv", en, LATIN)
# Translation lexicon: tools/translations.tsv + tools/vocab/*.tsv, merged per Amharic entry.
import glob

lexicon = {}
for src in [os.path.join(HERE, "translations.tsv")] + sorted(glob.glob(os.path.join(HERE, "vocab", "*.tsv"))):
    with open(src, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            t_am, t_en = line.split("\t")
            if not all(ETHIOPIC.match(part) for part in t_am.split(" ")):
                raise SystemExit(f"{src}: bad Amharic {t_am!r}")
            glosses = lexicon.setdefault(t_am, [])
            for g in t_en.split("|"):
                g = g.strip()
                if g and g not in glosses:
                    glosses.append(g)
with open(os.path.join(ASSETS, "translations.tsv"), "w", encoding="utf-8") as o:
    o.write("# generated by tools/build_dictionaries.py from tools/translations.tsv + tools/vocab/*.tsv\n")
    for t_am, glosses in lexicon.items():
        o.write(f"{t_am}\t{'|'.join(glosses)}\n")
n = len(lexicon)

# Every single Amharic word of the lexicon is also suggestible (low frequency, so the
# curated, frequency-ranked words keep their place).
extra = [w for w in lexicon if " " not in w and len(w) >= 2 and w not in am]
with open(os.path.join(ASSETS, "amharic_words.tsv"), "a", encoding="utf-8") as o:
    o.write("# lexicon words (tools/vocab)\n")
    for w in extra:
        o.write(f"{w}\t12\n")
am = am | set(extra)
print(f"amharic: {len(am)} words, english: {len(en)} words, translations: {n}")
